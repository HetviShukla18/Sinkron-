create table if not exists public.enquiries (
  id bigint generated by default as identity primary key,
  name text not null,
  company text,
  phone text not null,
  email text not null,
  application text,
  meter_type text,
  size text,
  quantity text,
  message text,
  email_status text default 'pending',
  telegram_status text default 'pending',
  whatsapp_status text not null default 'skipped' check (whatsapp_status in ('sent', 'failed', 'skipped')),
  created_at timestamptz default now()
);

-- Safe to rerun for existing installations; CREATE TABLE IF NOT EXISTS does
-- not add new columns. Historical enquiries did not attempt Cloud API delivery.
alter table public.enquiries add column if not exists whatsapp_status text not null
  default 'skipped' check (whatsapp_status in ('sent', 'failed', 'skipped'));

alter table public.enquiries enable row level security;

